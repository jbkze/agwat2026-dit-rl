"""All numbers that appear in the prose of the paper, as LaTeX macros. Rounding happens here.
The file is registered from the start, so that `\\input{generated/macros.tex}` always compiles;
until the campaigns have run it contains only its header."""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from analysis.collect import DERIVED

HEADER = "% Generated by analysis/macros.py. Do not edit; run make paper-assets.\n"


def _pct(x: float) -> str:
    return f"{100 * x:.1f}\\,\\%"


def generate(out: Path) -> None:
    lines = [HEADER]
    if (DERIVED / "benchmark_seasons.csv").exists() and (DERIVED / "oracle_ds.csv").exists():
        e1 = pd.read_csv(DERIVED / "benchmark_seasons.csv")
        e1 = e1[(e1["split"] == "test") & (e1["site"] == "nebraska")]
        oracle = pd.read_csv(DERIVED / "oracle_ds.csv")
        oracle = oracle[oracle["site"] == "nebraska"].groupby("budget_mm")["yield_t_ha"].mean()
        for agent, name in (("drl1", "DrlOne"), ("drl2", "DrlTwo")):
            means = e1[e1["agent"] == agent].groupby("budget_mm")["yield_t_ha"].mean()
            for budget, y in means.items():
                b = f"{budget:g}".replace(".", "")
                words = {"75": "SeventyFive", "100": "Hundred", "125": "HundredTwentyFive"}[b]
                lines.append(f"\\newcommand{{\\share{name}Nebraska{words}}}{{{_pct(y / oracle[budget])}}}")
        lines.append(f"\\newcommand{{\\nNebraskaTestYears}}{{{e1['year'].nunique()}}}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
