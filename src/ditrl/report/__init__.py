"""The report of this repository, rebuilt from the result tables after every new batch of results.

    ditrl report      figures and tables in reports/, the index reports/README.md, and the
                      results block of the main README.md

One module per topic; each returns its figures and tables (with what they show) and a few
sentences for the README. A module whose experiments have no results yet adds nothing.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

from ditrl.paths import REPO
from ditrl.plan import Plan
from ditrl.report import ablation, agreed, overview, paper, progress, training
from ditrl.report.core import Context, Section

MODULES = [overview, progress, agreed, ablation, training, paper]   # order of the index
REPORTS = REPO / "reports"
README = REPO / "README.md"
START, END = "<!-- report:start -->", "<!-- report:end -->"
# Figures shown in the README itself, in this order; the index lists all of them.
README_FIGURES = ["agreed_ablation_10_seeds", "agreed_ablation_5_seeds", "agreed_irrigation_timing", "ablation_main_effects",
                  "agreed_learning_curves", "paper_cwpf"]


def _relative(path: Path, start: Path) -> str:
    return Path(path).relative_to(start).as_posix()


def _index(sections: list[Section], out: Path) -> str:
    lines = ["# Report", "",
             "Built by `ditrl report` from the tables in `results/`; do not edit by hand. Every "
             "figure exists as PNG and PDF, every table as Markdown and CSV. The module named "
             "under each entry generates it (`src/ditrl/report/`). What the results mean is "
             "written down in [findings.md](findings.md).", ""]
    for entry in (e for s in sections for e in s.entries):
        is_figure = entry.path.suffix == ""
        lines += [f"## {entry.title}", "", entry.shows, ""]
        if is_figure:
            lines += [f"![{entry.title}]({_relative(entry.path.with_suffix('.png'), out)})", ""]
            files = f"`{_relative(entry.path.with_suffix('.png'), out)}`, `.pdf`"
        else:
            lines += [f"[Table]({_relative(entry.path, out)})", ""]
            files = f"`{_relative(entry.path, out)}`, `.csv`"
        lines += [f"Files: {files}. Generated by `{entry.module}`.", ""]
    return "\n".join(lines)


def _readme_block(sections: list[Section], ctx: Context) -> str:
    entries = {e.path.name: e for s in sections for e in s.entries}
    findings = [f for s in sections for f in s.findings]
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [START, "## Current results", "",
             f"Updated automatically on {stamp} by `ditrl report`; all figures and tables are in "
             f"[reports/](reports/README.md).", ""]
    lines += [f"- {finding}" for finding in findings]
    lines += ["", "[Findings so far](reports/findings.md) · "
              "[Progress per experiment](reports/tables/progress.md)", ""]
    for name in README_FIGURES:
        if name in entries:
            e = entries[name]
            lines += [f"**{e.title}.** {e.shows}", "",
                      f"![{e.title}]({_relative(e.path.with_suffix('.png'), REPO)})", ""]
    lines.append(END)
    return "\n".join(lines)


def build(plan: Plan, results: Path, out: Path = REPORTS, readme: Path = README) -> None:
    ctx = Context(plan, results, out)
    sections = [module.build(ctx) for module in MODULES]
    (out / "README.md").write_text(_index(sections, out), encoding="utf-8")
    text = readme.read_text(encoding="utf-8")
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        readme.write_text(head + _readme_block(sections, ctx) + tail, encoding="utf-8")
    count = sum(len(s.entries) for s in sections)
    print(f"report: {count} figures and tables in {out}")
