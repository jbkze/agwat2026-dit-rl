"""Every number in the prose of the paper, as LaTeX macros; rounding happens here. The file is
registered from the start, so that `\\input{generated/macros.tex}` always compiles; until the
experiments behind a number have run, its macro is missing."""

from __future__ import annotations

from pathlib import Path

from ditrl.analysis.data import oracle, test_seasons
from ditrl.plan import Plan

HEADER = "% Generated by ditrl.analysis.macros. Do not edit; run ditrl assets stage.\n"
# LaTeX command names allow no digits
NUMBER_WORDS = {75: "SeventyFive", 100: "Hundred", 125: "HundredTwentyFive"}


def _percent(x: float) -> str:
    return f"{100 * x:.1f}\\,\\%"


def generate(plan: Plan, results: Path, out: Path) -> None:
    lines = [HEADER]
    try:
        nebraska = test_seasons(plan, results, "benchmark").query("site == 'nebraska'")
    except FileNotFoundError:
        nebraska = None
    if nebraska is not None:
        reference = oracle(plan, results, "ds").query("site == 'nebraska'")
        ceiling = reference.groupby("budget_mm")["yield_t_ha"].mean()
        for method, name in (("drl1", "DrlOne"), ("drl2", "DrlTwo")):
            means = nebraska[nebraska["method"] == method].groupby("budget_mm")["yield_t_ha"].mean()
            for budget, y in means.items():
                words = NUMBER_WORDS[int(budget)]
                lines.append(f"\\newcommand{{\\share{name}Nebraska{words}}}"
                             f"{{{_percent(y / ceiling[budget])}}}")
        lines.append(f"\\newcommand{{\\nNebraskaTestYears}}{{{nebraska['year'].nunique()}}}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
