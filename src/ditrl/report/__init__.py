"""The report of this repository, rebuilt from the result tables after every new batch of results.

    ditrl report      figures and tables in reports/, the index reports/README.md, the central
                      findings reports/findings.md, and the results block of the main README.md

One module per topic; each returns a section with its figures and tables (with what they show) and
a few status sentences for the README. A module whose experiments have no results yet adds nothing.

The central findings are written by hand in config/findings.md. Their numbers are placeholders
that are filled in from the current tables on every build, so the text never quotes old numbers:

    {{terminal@tunis 300}}                effect of the sensitivity question `terminal` there
    {{figure:agreed_irrigation_timing}}   a figure of reports/figures
"""

from __future__ import annotations

import datetime as dt
import math
import re
import shutil
from pathlib import Path

from ditrl.paths import REPO
from ditrl.plan import Plan
from ditrl.report import agreed, overview, paper, progress, sensitivity, training
from ditrl.report.core import Context, Section

MODULES = [overview, progress, sensitivity, agreed, paper, training]   # order of the index
REPORTS = REPO / "reports"
README = REPO / "README.md"
FINDINGS = REPO / "config" / "findings.md"
START, END = "<!-- report:start -->", "<!-- report:end -->"
EFFECT = re.compile(r"\{\{(\w+)@(\w+) (\d+(?:\.\d+)?)\}\}")
FIGURE = re.compile(r"\{\{figure:(\w+)\}\}")


def _relative(path: Path, start: Path) -> str:
    return Path(path).relative_to(start).as_posix()


def _index(sections: list[Section], out: Path) -> str:
    lines = ["# Report", "",
             "Built by `ditrl report` from the tables in `results/`; do not edit by hand. Every "
             "figure exists as PNG and PDF, every table as Markdown and CSV. The module named "
             "under each entry generates it (`src/ditrl/report/`). The central findings are in "
             "[findings.md](findings.md).", ""]
    for section in (s for s in sections if s.entries):
        lines += [f"## {section.title}", ""]
        for entry in section.entries:
            lines += [f"### {entry.title}", "", entry.shows, ""]
            if entry.path.suffix == "":
                png = _relative(entry.path.with_suffix(".png"), out)
                lines += [f"![{entry.title}]({png})", "",
                          f"Files: `{png}`, `.pdf`. Generated by `{entry.module}`.", ""]
            else:
                md = _relative(entry.path, out)
                lines += [f"[Table]({md})", "",
                          f"Files: `{md}`, `.csv`. Generated by `{entry.module}`.", ""]
    return "\n".join(lines)


def _effect(ctx: Context, match: re.Match) -> str:
    qid, site, budget = match.group(1), match.group(2), float(match.group(3))
    t = ctx.facts.get("sensitivity")
    if t is None:
        return "(pending)"
    row = t[(t["question"] == qid) & (t["kind"] == "effect") & (t["site"] == site)
            & (t["budget_mm"] == budget)]
    if row.empty or math.isnan(row["effect"].iloc[0]):
        return "(pending)"
    r = row.iloc[0]
    partial = f", {int(r['done'])} of {int(r['planned'])} runs" if r["done"] < r["planned"] else ""
    return f"{r['effect']:+.2f} t/ha [{r['ci_low']:+.2f}, {r['ci_high']:+.2f}{partial}]"


def findings(ctx: Context, base: Path) -> str:
    """config/findings.md without its leading comment, numbers and figures filled in, figure
    paths relative to `base`."""
    if not FINDINGS.exists():
        return ""
    text = FINDINGS.read_text(encoding="utf-8")
    if text.startswith("<!--"):
        text = text.split("-->", 1)[1].lstrip()
    text = FIGURE.sub(lambda m: f"![{m.group(1)}]"
                      f"({_relative(ctx.figures / (m.group(1) + '.png'), base)})", text)
    return EFFECT.sub(lambda m: _effect(ctx, m), text)


def _readme_block(sections: list[Section], ctx: Context) -> str:
    entries = {e.path.name: e for s in sections for e in s.entries}
    status = " ".join(f for s in sections for f in s.findings)
    stamp = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [START, "## Current results", "",
             f"Updated automatically on {stamp} by `ditrl report`. {status} "
             f"[Progress per experiment](reports/tables/progress.md)", "",
             "### Central findings", "", findings(ctx, REPO).rstrip(), ""]
    if "sensitivity" in entries:
        e = entries["sensitivity"]
        lines += ["### What changes what", "", e.shows, "",
                  f"![{e.title}]({_relative(e.path.with_suffix('.png'), REPO)})", "",
                  "[Numbers](reports/tables/sensitivity.md) · "
                  "[Agreed ablation for the co-author](reports/README.md#agreed-ablation) · "
                  "[All figures and tables](reports/README.md)", ""]
    lines.append(END)
    return "\n".join(lines)


def build(plan: Plan, results: Path, out: Path = REPORTS, readme: Path = README) -> None:
    for folder in ("figures", "tables"):   # nothing stale survives; unchanged files stay identical
        shutil.rmtree(out / folder, ignore_errors=True)
    ctx = Context(plan, results, out)
    sections = [module.build(ctx) for module in MODULES]
    (out / "README.md").write_text(_index(sections, out), encoding="utf-8")
    (out / "findings.md").write_text(
        "# Central findings\n\nWritten in `config/findings.md`; the numbers are filled in from the "
        "current results by `ditrl report`.\n\n" + findings(ctx, out), encoding="utf-8")
    text = readme.read_text(encoding="utf-8")
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        readme.write_text(head + _readme_block(sections, ctx) + tail, encoding="utf-8")
    count = sum(len(s.entries) for s in sections)
    print(f"report: {count} figures and tables in {out}")
